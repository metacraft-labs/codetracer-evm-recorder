# The one machine-local line of a current managed body (reprobuild PG-15).
# Reprobuild's `vcsManagedHookBody` writes it at column zero as
# `REPRO_REFUSAL_RECORD_DIR=<quoteShellPosix(dir)>`, where `dir` is "" outside
# an initialized workspace and otherwise `managedHookRefusalRecordDir`:
# `commitHookReportDir(W)/managed-hook-refusals/<blake3 hex of the canonical
# checkout root>`, with `commitHookReportDir(W)` = `W/.repro/build/reports`
# and W the enclosing workspace root. The exclusive factory root is never a
# workspace, so every factory body carries `''`; a real checkout's bodies differ
# from it in exactly this value. Only the indented lines that READ the variable
# appear elsewhere, so a column-zero prefix match finds the assignment alone.
REFUSAL_DIR_ASSIGNMENT = b"REPRO_REFUSAL_RECORD_DIR="
EMPTY_SHELL_WORD = b"''"
REFUSAL_RECORD_REPORT_PARTS = (".repro", "build", "reports", "managed-hook-refusals")
# Nim's std/os quoteShellPosix leaves a word bare when every byte is in this set.
# https://nim-lang.org/docs/os.html#quoteShellPosix%2Cstring
SHELL_SAFE_BYTES = frozenset(b"%+-./_:=@0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz")


def quote_shell_posix(word: bytes) -> bytes:
    """Byte-exact port of Nim's std/os quoteShellPosix, which reprobuild uses."""
    if not word:
        return EMPTY_SHELL_WORD
    if all(byte in SHELL_SAFE_BYTES for byte in word):
        return word
    return b"'" + word.replace(b"'", b"'\"'\"'") + b"'"


def unquote_shell_posix_word(quoted: bytes) -> bytes:
    """Propose the word `quote_shell_posix` would have quoted to `quoted`.

    Mirrors reprobuild's `unquoteShellPosixWord`. Only a proposal: callers
    re-quote it and require byte equality, so a misreading can only refuse."""
    if len(quoted) >= 2 and quoted[:1] == b"'" and quoted[-1:] == b"'":
        return quoted[1:-1].replace(b"'\"'\"'", b"'")
    return quoted


def split_refusal_record_dir(body: bytes) -> tuple[bytes, bytes | None]:
    """Return the body as the factory renders it, plus the baked value.

    The single column-zero assignment's value is replaced by `''`; every other
    byte is returned unchanged, so the result's digest still pins them all. A
    body without the assignment (every 76659f legacy body) returns `None`."""
    lines = body.split(b"\n")
    found = [i for i, line in enumerate(lines) if line.startswith(REFUSAL_DIR_ASSIGNMENT)]
    if not found:
        return body, None
    if len(found) != 1:
        raise RuntimeError("managed hook body assigns its refusal-record directory more than once")
    index = found[0]
    value = lines[index][len(REFUSAL_DIR_ASSIGNMENT):]
    lines[index] = REFUSAL_DIR_ASSIGNMENT + EMPTY_SHELL_WORD
    return b"\n".join(lines), value


def render_refusal_record_dir(factory_body: bytes, value: bytes) -> bytes:
    """Put `value` into a factory body's single `''` assignment."""
    canonical, current = split_refusal_record_dir(factory_body)
    if current != EMPTY_SHELL_WORD or canonical != factory_body:
        raise RuntimeError("factory body does not carry exactly one empty refusal-record directory")
    lines = factory_body.split(b"\n")
    index = lines.index(REFUSAL_DIR_ASSIGNMENT + EMPTY_SHELL_WORD)
    lines[index] = REFUSAL_DIR_ASSIGNMENT + value
    return b"\n".join(lines)


def validate_refusal_record_dir(value: bytes, root: Path | None) -> None:
    """Admit `''`, or the exact quoted `<W>/.repro/build/reports/managed-hook-refusals/<k>`.

    W must be the owning checkout root or one of its ancestors and k 64
    lowercase hex characters. k is checked for form only: it is reprobuild's
    domain-separated BLAKE3 of the canonical root, which this installer does
    not declare."""
    if value == EMPTY_SHELL_WORD:
        return
    decoded = unquote_shell_posix_word(value)
    if quote_shell_posix(decoded) != value:
        raise RuntimeError("managed hook refusal-record directory is not canonical shell quoting: " + repr(value))
    if root is None:
        raise RuntimeError("managed hook refusal-record directory has no owning checkout to anchor it: " + repr(value))
    path = os.fsdecode(decoded)
    record = Path(path)
    # Lexical checks only: the directory need not exist, and it must already be
    # spelled the way reprobuild spells it (absolute, normalized, no `..`).
    if not record.is_absolute() or os.path.normpath(path) != path or ".." in record.parts:
        raise RuntimeError("managed hook refusal-record directory is not a normalized absolute path: " + repr(value))
    key = record.name
    if len(key) != 64 or any(c not in "0123456789abcdef" for c in key):
        raise RuntimeError("managed hook refusal-record directory key is not 64 lowercase hex characters: " + repr(value))
    report = record.parent
    if report.parts[-len(REFUSAL_RECORD_REPORT_PARTS):] != REFUSAL_RECORD_REPORT_PARTS:
        raise RuntimeError("managed hook refusal-record directory is not beneath .repro/build/reports/managed-hook-refusals: " + repr(value))
    workspace = Path(*report.parts[:-len(REFUSAL_RECORD_REPORT_PARTS)])
    anchors = {root.absolute(), *root.absolute().parents}
    if workspace not in anchors:
        raise RuntimeError("managed hook refusal-record directory is outside the checkout and its ancestors: " + repr(value))


def qualified_managed_body(name: str, body: bytes, root: Path | None) -> tuple[bool, bytes | None]:
    """Admit a current or legacy managed body, allowing only its PG-15 value to vary.

    Returns whether the body is qualified and the value it carries (None for a
    body without the assignment). A qualified body with an inadmissible value
    refuses by name instead of returning False."""
    canonical, value = split_refusal_record_dir(body)
    if not qualified_managed_prior(name, hashlib.sha256(canonical).hexdigest()):
        return False, value
    if value is not None:
        validate_refusal_record_dir(value, root)
    return True, value


def require_one_refusal_record_dir(values: dict[str, bytes | None]) -> bytes | None:
    """Every managed body of one inventory must advertise the same directory."""
    carried = {value for value in values.values() if value is not None}
    if len(carried) > 1:
        carriers = sorted((n, v) for n, v in values.items() if v is not None)
        raise RuntimeError("managed hook bodies carry different refusal-record directories: " + repr(carriers))
    return next(iter(carried), None)


