NATIVE_TEMPLATE = b'#!/bin/sh\n# File generated by prek: https://github.com/j178/prek\n# ID: 182c10f181da4464a3eec51b83331688\n\nHERE="$(cd "$(dirname "$0")" && pwd)"\nPREK="@OWNING_PREK_EXECUTABLE@"\n\n# Check if the full path to prek is executable, otherwise fallback to PATH\nif [ ! -x "$PREK" ]; then\n    PREK="prek"\nfi\n\nexec "$PREK" hook-impl --hook-dir "$HERE" --script-version 4 --hook-type=pre-commit -- "$@"\n\n'

def native_generated_body(prek: str, hook_type: str = "pre-commit") -> bytes:
    if hook_type not in ("pre-commit", "pre-push"):
        raise RuntimeError("unqualified native hook type")
    return NATIVE_TEMPLATE.replace(b"@OWNING_PREK_EXECUTABLE@", os.fsencode(prek)).replace(
        b"--hook-type=pre-commit", os.fsencode("--hook-type=" + hook_type))

def canonical_body(prek: str, hook_type: str = "pre-commit") -> bytes:
    native = native_generated_body(prek, hook_type)
    first, rest = native.split(b"\n", 1)
    return first + b"\n" + EXPORT + rest

def canonical_generated_body(body: bytes, prek: str, mode: int, hook_type: str = "pre-commit") -> bytes:
    if mode != 0o755 or body != native_generated_body(prek, hook_type):
        raise RuntimeError("unexpected exact owning native Prek hook body or mode")
    return canonical_body(prek, hook_type)

def validate_prior_owned_body(body: bytes, mode: int, prek: str) -> None:
    if mode != 0o755:
        raise RuntimeError("former owning local hook mode changed")
    if body not in (native_generated_body(prek), canonical_body(prek)):
        raise RuntimeError("unknown or modified owning local hook body")

