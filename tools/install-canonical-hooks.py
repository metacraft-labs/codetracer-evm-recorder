def complete_hook_inventory(hooks: Path, prek: str) -> dict[str, tuple[bytes, int]]:
    result = {}
    if not hooks.exists():
        return result
    for path in hooks.iterdir():
        info = path.lstat()
        if stat.S_ISLNK(info.st_mode):
            raise RuntimeError(f"unowned hook entry symlink: {path.name}")
        if not stat.S_ISREG(info.st_mode):
            raise RuntimeError(f"unowned hook entry type: {path.name}")
        body = path.read_bytes()
        mode = stat.S_IMODE(info.st_mode)
        digest = hashlib.sha256(body).hexdigest()
        expected = KNOWN_MANAGED_BODIES.get(path.name)
        allowed = qualified_managed_prior(path.name, digest)
        if path.name == "pre-commit":
            allowed = allowed or body in (native_generated_body(prek), canonical_body(prek))
        if path.name in KNOWN_GIT_SAMPLES:
            allowed = digest in KNOWN_GIT_SAMPLES[path.name]
        if path.name in ("pre-commit.repro-local", "pre-push.repro-local"):
            hook_type = path.name.removesuffix(".repro-local")
            allowed = body in (native_generated_body(prek, hook_type), canonical_body(prek, hook_type))
        for prefix, hook_type in (("pre-commit.repro-local.backup-", "pre-commit"),
                                    ("retired-owned-pre-push-local-", "pre-push")):
            if path.name.startswith(prefix):
                allowed = path.name == prefix + digest and body in (native_generated_body(prek, hook_type), canonical_body(prek, hook_type))
        if not allowed or mode != 0o755:
            raise RuntimeError(f"unknown or modified hook entry body or mode: {path.name}")
        result[path.name] = (body, mode)
    return result


def pre_push_inventory(hooks: Path, prek: str) -> dict[str, tuple[bytes, int]]:
    inventory = {}
    if not hooks.exists():
        return inventory
    for path in hooks.iterdir():
        if not path.name.startswith("pre-push"):
            continue
        expected = KNOWN_MANAGED_BODIES.get(path.name)
        if path.name == "pre-push.repro-local":
            expected = "native-or-canonical-owning-prek-body"
        sample = path.name == "pre-push.sample"
        if expected is None and not sample:
            raise RuntimeError(f"unknown pre-push hook entry: {path.name}")
        metadata = path.lstat()
        if not stat.S_ISREG(metadata.st_mode):
            raise RuntimeError(f"unowned pre-push hook type: {path.name}")
        body = path.read_bytes()
        mode = stat.S_IMODE(metadata.st_mode)
        digest = hashlib.sha256(body).hexdigest()
        qualified_body = digest in KNOWN_GIT_PRE_PUSH_SAMPLE_BODIES if sample else qualified_managed_prior(path.name, digest)
        if path.name == "pre-push.repro-local":
            qualified_body = qualified_body or body in (native_generated_body(prek, "pre-push"), canonical_body(prek, "pre-push"))
        if mode != 0o755 or not qualified_body:
            raise RuntimeError(f"modified pre-push hook body or mode: {path.name}")
        inventory[path.name] = (body, mode)
    return inventory

